#!/usr/bin/env python3
"""Generate the fixed-column GPU factorization without changing pivot arithmetic."""
import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
START = "  attributes(device) subroutine air5_lu_factor_6_gpu("
END = "  end subroutine air5_lu_factor_6_gpu"


def factorization():
    lines = [
        "  attributes(device) subroutine air5_lu_factor_6_gpu(matrix,lu,pivots,status)",
        "    real(real64), intent(in) :: matrix(linear_size,linear_size)",
        "    real(real64), intent(out) :: lu(linear_size,linear_size)",
        "    integer, intent(out) :: pivots(linear_size), status",
        "    real(real64) :: scale1,scale2,scale3,scale4,scale5,scale6",
        "    real(real64) :: row_max,scaled_pivot,best_scaled_pivot,value,scale_buffer",
        "    integer :: column,pivot,row,item",
        "",
        "    ! Generated by scripts/gpu_validation/generate_air5_lu6.py.",
        "    do row=1,linear_size",
        "      pivots(row)=row",
        "      row_max=0.0_real64",
        "      do column=1,linear_size",
        "        value=matrix(row,column)",
        "        lu(row,column)=value",
        "        if(.not.air5_finite_gpu(value)) then",
        "          status=chemistry_status_nonfinite",
        "          return",
        "        endif",
        "        row_max=max(row_max,abs(value))",
        "      enddo",
        "      if(row_max==0.0_real64) then",
        "        status=chemistry_status_linear_failure",
        "        return",
        "      endif",
        "      select case(row)",
    ]
    for row in range(1, 7):
        lines += [f"      case({row})", f"        scale{row}=row_max"]
    lines += ["      end select", "    enddo", ""]
    for column in range(1, 6):
        lines += [
            f"    pivot={column}",
            f"    best_scaled_pivot=abs(lu({column},{column}))/scale{column}",
        ]
        for row in range(column + 1, 7):
            lines += [
                f"    scaled_pivot=abs(lu({row},{column}))/scale{row}",
                "    if(scaled_pivot>best_scaled_pivot) then",
                f"      pivot={row}",
                "      best_scaled_pivot=scaled_pivot",
                "    endif",
            ]
        lines += [
            "    if(best_scaled_pivot<=64.0_real64*epsilon(1.0_real64)) then",
            "      status=chemistry_status_linear_failure",
            "      return",
            "    endif",
            f"    pivots({column})=pivot",
            f"    if(pivot/={column}) then",
            "      do item=1,linear_size",
            f"        value=lu({column},item)",
            f"        lu({column},item)=lu(pivot,item)",
            "        lu(pivot,item)=value",
            "      enddo",
            f"      scale_buffer=scale{column}",
            "      select case(pivot)",
        ]
        for row in range(column + 1, 7):
            lines += [
                f"      case({row})",
                f"        scale{column}=scale{row}",
                f"        scale{row}=scale_buffer",
            ]
        lines += [
            "      end select",
            "    endif",
            f"    do row={column+1},linear_size",
            f"      lu(row,{column})=lu(row,{column})/lu({column},{column})",
            f"      do item={column+1},linear_size",
            f"        lu(row,item)=lu(row,item)-lu(row,{column})*lu({column},item)",
            "      enddo",
            "    enddo",
            "",
        ]
    lines += [
        "    if(abs(lu(6,6))/scale6<=64.0_real64*epsilon(1.0_real64)) then",
        "      status=chemistry_status_linear_failure",
        "      return",
        "    endif",
        "    do row=1,linear_size",
        "      do column=1,linear_size",
        "        if(.not.air5_finite_gpu(lu(row,column))) then",
        "          status=chemistry_status_linear_failure",
        "          return",
        "        endif",
        "      enddo",
        "    enddo",
        "    status=chemistry_status_ok",
        END,
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    path = ROOT / "src_gpu/chemistry_kinetics_gpu.cuf"
    source = path.read_text()
    start, stop = source.index(START), source.index(END) + len(END)
    generated = factorization()
    if args.write:
        path.write_text(source[:start] + generated + source[stop:])
    elif source[start:stop] != generated:
        raise SystemExit("GPU LU6 body differs from generator; use --write after reviewing changes")


if __name__ == "__main__":
    main()
