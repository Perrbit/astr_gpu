"""Emit the fixed W1 tables from the SHA256-pinned scalar-reference snapshot."""
import argparse
from pathlib import Path

import numpy as np

from run_keep_w1_normal_gate import audit, operators, sparse
from check_keep_w1_shear_heat import normal_operators


def initializer(seq, convert, columns):
    values = list(map(convert,seq))
    return '{\n'+''.join('        '+', '.join(values[i:i+columns])+',\n' for i in range(0,len(values),columns))+'    }'


def generate(source):
    left,inside = operators(source)
    verification = audit(source)
    h,d,_,_,gamma = normal_operators(25,left,inside,verification['separate_viscous_d1_shift'])
    begin,value_idx,coef_idx,coef = sparse(left,inside)
    real = lambda x: format(float(x), '.17g')
    print('''#pragma once
#include "keep_w1_tensor_math.h"

// Generated by tests/gpu_backend/generate_keep_w1_tables.py; do not edit.
// Variable-coefficient data: Mattsson (2012), doi:10.1007/s10915-011-9525-z,
// including erratum, via SummationByPartsOperators.jl (MIT, see keep_w1_tables.LICENSE).
// Frozen Mattsson2012.jl SHA256:
// 54529672355acdfbe843770c278bb4c3909148a4993b05ba24d5dcb5a65da691
namespace astr {
namespace w1 {
static constexpr TensorTable solver_table{ {''')
    for data in (begin,value_idx,coef_idx):
        print('    '+initializer(data,str,20)+',')
    print('    '+initializer(coef,real,4)+',')
    print('    '+initializer(h[:6],real,3)+', '+real(gamma)+'\n}, {')
    for row in d[:6,:9]:
        print('    '+initializer(row,real,3)+',')
    print('} };\n} // namespace w1\n} // namespace astr')


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('coefficient_source',type=Path)
    generate(parser.parse_args().coefficient_source)
